function attachAccountIds<T extends { id: string; platform: Platform; accountId?: string }>(rows: T[]) {
  for (const row of rows) {
    if (row.accountId) continue
    const pool = accountPools[row.platform]
    const seed = [...row.id].reduce((acc, ch) => acc + ch.charCodeAt(0), 0)
    row.accountId = pool[seed % pool.length]
  }
}

